#!/usr/bin/env python3
"""
make_firmware_cpp.py — generate FwBinary.cpp for SimpleMtkBtFw

Firmware .bin files are zlib-compressed and embedded as C++ byte arrays,
compatible with FwData.h's FwDesc / fwList interface.

Usage:
  python3 make_firmware_cpp.py -o FwBinary.cpp fw1.bin fw2.bin [...]
  python3 make_firmware_cpp.py -o FwBinary.cpp --fw-dir ./firmwares

The generated file must be placed next to FwData.h (default:
SimpleMtkBtFw/FwBinary.cpp).

Where to get firmware:
  - laobamac/SimpleMtkBtFw releases (BT_RAM_CODE_MT7961_*.bin, BT_RAM_CODE_MT7922_*.bin)
  - linux-firmware repository (kernel.org)
  - Windows driver packages from your laptop/PC vendor (newer versions,
    e.g. BT_RAM_CODE_MT7961_1_2_hdr.bin from MediaTek Windows drivers)
"""
import argparse
import glob
import os
import re
import zlib


def varname_for(path: str) -> str:
    base = os.path.splitext(os.path.basename(path))[0]
    v = re.sub(r"[^0-9A-Za-z]", "_", base)
    if v[0].isdigit():
        v = "fw_" + v
    return v + "_bin"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("bins", nargs="*", help="firmware .bin files")
    ap.add_argument("--fw-dir", help="directory containing .bin files")
    ap.add_argument("-o", "--output", default="FwBinary.cpp")
    args = ap.parse_args()

    files = list(args.bins)
    if args.fw_dir:
        files += sorted(glob.glob(os.path.join(args.fw_dir, "*.bin")))
    if not files:
        raise SystemExit("error: no firmware .bin files given")

    seen = set()
    entries = []
    for f in files:
        var = varname_for(f)
        if var in seen:
            raise SystemExit(f"error: duplicate variable name for {f}")
        seen.add(var)
        data = open(f, "rb").read()
        comp = zlib.compress(data, 9)
        entries.append((os.path.basename(f), var, comp))

    out = []
    out.append("//\n//  FwBinary.cpp — GENERATED FILE, do not edit.\n"
               "//  Generated by tools/make_firmware_cpp.py\n//\n")
    out.append('#include "FwData.h"\n\n')

    for _, var, comp in entries:
        out.append(f"const unsigned char {var}[] = {{")
        hexb = [f"0x{b:02X}" for b in comp]
        # 16 bytes per line
        for i in range(0, len(hexb), 16):
            out.append(",".join(hexb[i:i + 16]) + ",")
        out.append("};\n")
        out.append(f"const long int {var}_size = sizeof({var});\n\n")

    out.append("const struct FwDesc fwList[] = {\n")
    for name, var, _ in entries:
        out.append(f'    {{MTK_BT_FW("{name}", {var}, {var}_size)}},\n')
    out.append("};\n")
    out.append(f"const int fwNumber = {len(entries)};\n")

    with open(args.output, "w") as fh:
        fh.write("".join(out))
    print(f"wrote {args.output} with {len(entries)} firmware file(s):")
    for name, _, comp in entries:
        print(f"  {name} ({len(comp)} bytes compressed)")


if __name__ == "__main__":
    main()
